import { CheckSquare, Square } from 'lucide-react';
import { useCallback, useEffect, useState } from 'react';
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  Pie,
  PieChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from 'recharts';
import { useApp } from '../context/AppContext';
import { api } from '../lib/api';
import { convertCurrency, formatCompactMoney, formatMoney } from '../lib/currency';
import { t } from '../lib/i18n';

interface DashboardResponse {
  kpis: {
    openPipelineAED: number;
    weightedForecastAED: number;
    wonThisMonthAED: number;
    wonThisMonthCount: number;
    lostThisMonthAED: number;
    lostThisMonthCount: number;
    winRate: number;
    leadConversionRate: number;
    totalLeads: number;
    tasksDueTodayCount: number;
    totalMrrAED: number;
  };
  pipelineByStage: Array<{ stage: string; count: number; valueAED: number; weightedAED: number }>;
  leadsBySource: Array<{ source: string; count: number }>;
  tasksDueToday: Array<{
    id: string;
    subject: string;
    priority: string;
    dueDate: string;
    autoGenerated: boolean;
    account?: { name: string } | null;
    deal?: { title: string } | null;
  }>;
  leaderboard: Array<{
    id: string;
    name: string;
    wonAED: number;
    pipelineAED: number;
    dealsCount: number;
  }>;
  upcomingRenewals: Array<{
    id: string;
    contractNumber: string;
    title: string;
    accountName: string;
    endDate: string;
    daysLeft: number;
    arrAED: number;
  }>;
}

const CHART_COLORS = ['#2563eb', '#0ea5e9', '#14b8a6', '#f59e0b', '#6366f1', '#16a34a', '#dc2626'];

export function DashboardView() {
  const { currency, language, user, setActiveModule, showToast } = useApp();
  const [data, setData] = useState<DashboardResponse | null>(null);
  const [loading, setLoading] = useState(true);

  const load = useCallback(async () => {
    try {
      const res = await api<DashboardResponse>('/dashboard');
      setData(res);
    } catch (err) {
      showToast(err instanceof Error ? err.message : 'Failed to load dashboard', 'error');
    } finally {
      setLoading(false);
    }
  }, [showToast]);

  useEffect(() => {
    load();
  }, [load]);

  const toggleTask = async (taskId: string) => {
    if (user?.role === 'READ_ONLY') return;
    try {
      await api(`/activities/${taskId}`, {
        method: 'PATCH',
        body: JSON.stringify({ completed: true }),
      });
      showToast('Task marked completed');
      load();
    } catch (err) {
      showToast(err instanceof Error ? err.message : 'Failed to complete task', 'error');
    }
  };

  if (loading || !data) {
    return (
      <div className="space-y-6">
        <div className="grid grid-cols-2 lg:grid-cols-6 gap-4">
          {Array.from({ length: 6 }).map((_, idx) => (
            <div
              key={idx}
              className="h-24 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 animate-pulse"
            />
          ))}
        </div>
        <div className="h-72 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800 animate-pulse" />
      </div>
    );
  }

  const stageChartData = data.pipelineByStage.map((item) => ({
    stage: item.stage.replace('CLOSED_', '').replace(/_/g, ' '),
    value: Math.round(convertCurrency(item.valueAED, 'AED', currency)),
    weighted: Math.round(convertCurrency(item.weightedAED, 'AED', currency)),
    count: item.count,
  }));

  const kpiCards = [
    {
      label: t(language, 'openPipeline'),
      value: formatCompactMoney(data.kpis.openPipelineAED, 'AED', currency),
      sub: `${data.pipelineByStage.filter((s) => !s.stage.startsWith('CLOSED')).reduce((a, b) => a + b.count, 0)} open deals`,
    },
    {
      label: t(language, 'weightedForecast'),
      value: formatCompactMoney(data.kpis.weightedForecastAED, 'AED', currency),
      sub: 'Probability-adjusted',
    },
    {
      label: t(language, 'wonThisMonth'),
      value: formatCompactMoney(data.kpis.wonThisMonthAED, 'AED', currency),
      sub: `${data.kpis.wonThisMonthCount} closed won · ${data.kpis.winRate}% win rate`,
      tone: 'text-emerald-600 dark:text-emerald-400',
    },
    {
      label: t(language, 'lostThisMonth'),
      value: formatCompactMoney(data.kpis.lostThisMonthAED, 'AED', currency),
      sub: `${data.kpis.lostThisMonthCount} closed lost`,
      tone: 'text-red-600 dark:text-red-400',
    },
    {
      label: t(language, 'conversionRate'),
      value: `${data.kpis.leadConversionRate}%`,
      sub: `${data.kpis.totalLeads} active leads`,
    },
    {
      label: t(language, 'monthlyRecurring'),
      value: formatCompactMoney(data.kpis.totalMrrAED, 'AED', currency),
      sub: 'Active contracts MRR',
    },
  ];

  return (
    <div className="space-y-6">
      {/* KPI Strip */}
      <div className="grid grid-cols-2 md:grid-cols-3 xl:grid-cols-6 gap-4">
        {kpiCards.map((kpi) => (
          <div
            key={kpi.label}
            className="p-4 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800"
          >
            <div className="text-xs font-medium text-slate-500 dark:text-slate-400 truncate">
              {kpi.label}
            </div>
            <div
              className={`mt-1.5 text-xl font-bold font-mono tabular-nums ${
                kpi.tone || 'text-slate-900 dark:text-slate-100'
              }`}
            >
              {kpi.value}
            </div>
            <div className="mt-1 text-[11px] text-slate-500 dark:text-slate-400 truncate">
              {kpi.sub}
            </div>
          </div>
        ))}
      </div>

      {/* Charts Row */}
      <div className="grid lg:grid-cols-3 gap-6">
        <div className="lg:col-span-2 p-5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          <div className="flex items-center justify-between mb-4">
            <div>
              <h2 className="font-display text-base font-semibold text-slate-900 dark:text-slate-100">
                {t(language, 'pipelineByStage')}
              </h2>
              <p className="text-xs text-slate-500 dark:text-slate-400">
                Total value vs probability-weighted forecast ({currency})
              </p>
            </div>
            <button
              onClick={() => setActiveModule('deals')}
              className="text-xs font-medium text-blue-600 dark:text-blue-400 hover:underline whitespace-nowrap"
            >
              Open Pipeline
            </button>
          </div>
          <div className="h-72">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={stageChartData} margin={{ top: 8, right: 12, left: 0, bottom: 8 }}>
                <CartesianGrid strokeDasharray="3 3" stroke="#334155" opacity={0.2} />
                <XAxis dataKey="stage" tick={{ fontSize: 11, fill: '#94a3b8' }} />
                <YAxis tick={{ fontSize: 11, fill: '#94a3b8' }} />
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#0f172a',
                    borderColor: '#1e293b',
                    borderRadius: '8px',
                    color: '#f8fafc',
                    fontSize: '12px',
                  }}
                />
                <Bar dataKey="value" name={`Pipeline (${currency})`} fill="#2563eb" radius={[4, 4, 0, 0]} />
                <Bar dataKey="weighted" name={`Weighted (${currency})`} fill="#14b8a6" radius={[4, 4, 0, 0]} />
              </BarChart>
            </ResponsiveContainer>
          </div>
        </div>

        <div className="p-5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          <div className="flex items-center justify-between mb-4">
            <h2 className="font-display text-base font-semibold text-slate-900 dark:text-slate-100">
              {t(language, 'leadsBySource')}
            </h2>
            <button
              onClick={() => setActiveModule('leads')}
              className="text-xs font-medium text-blue-600 dark:text-blue-400 hover:underline whitespace-nowrap"
            >
              View Leads
            </button>
          </div>
          <div className="h-52">
            <ResponsiveContainer width="100%" height="100%">
              <PieChart>
                <Pie
                  data={data.leadsBySource}
                  dataKey="count"
                  nameKey="source"
                  cx="50%"
                  cy="50%"
                  innerRadius={45}
                  outerRadius={78}
                  paddingAngle={2}
                >
                  {data.leadsBySource.map((entry, index) => (
                    <Cell key={entry.source} fill={CHART_COLORS[index % CHART_COLORS.length]} />
                  ))}
                </Pie>
                <Tooltip
                  contentStyle={{
                    backgroundColor: '#0f172a',
                    borderColor: '#1e293b',
                    borderRadius: '8px',
                    color: '#f8fafc',
                    fontSize: '12px',
                  }}
                />
              </PieChart>
            </ResponsiveContainer>
          </div>
          <div className="mt-2 space-y-1.5">
            {data.leadsBySource.map((s, i) => (
              <div key={s.source} className="flex items-center justify-between text-xs">
                <span className="text-slate-600 dark:text-slate-300 flex items-center gap-2">
                  <span
                    className="w-2.5 h-2.5 rounded-sm inline-block"
                    style={{ backgroundColor: CHART_COLORS[i % CHART_COLORS.length] }}
                  />
                  {s.source.replace(/_/g, ' ')}
                </span>
                <span className="font-mono tabular-nums text-slate-900 dark:text-slate-100">
                  {s.count}
                </span>
              </div>
            ))}
          </div>
        </div>
      </div>

      {/* Operational Widgets Row */}
      <div className="grid lg:grid-cols-3 gap-6">
        {/* Tasks Due Today */}
        <div className="p-5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          <div className="flex items-center justify-between mb-4">
            <h2 className="font-display text-base font-semibold text-slate-900 dark:text-slate-100">
              {t(language, 'tasksDueToday')}
            </h2>
            <span className="text-xs font-mono tabular-nums text-slate-500">
              {data.kpis.tasksDueTodayCount} open
            </span>
          </div>
          {data.tasksDueToday.length === 0 ? (
            <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
              All scheduled follow-ups for today are complete.
            </div>
          ) : (
            <div className="divide-y divide-slate-100 dark:divide-slate-800">
              {data.tasksDueToday.map((task) => (
                <div key={task.id} className="py-2.5 flex items-start gap-2.5">
                  <button
                    onClick={() => toggleTask(task.id)}
                    className="mt-0.5 text-slate-400 hover:text-blue-600 shrink-0"
                    title="Complete task"
                  >
                    {false ? <CheckSquare className="w-4 h-4" /> : <Square className="w-4 h-4" />}
                  </button>
                  <div className="min-w-0 flex-1">
                    <div className="text-sm font-medium text-slate-900 dark:text-slate-100 truncate">
                      {task.subject}
                    </div>
                    <div className="text-xs text-slate-500 dark:text-slate-400 flex items-center gap-1.5">
                      <span>{task.account?.name || task.deal?.title || 'General'}</span>
                      <span>·</span>
                      <span
                        className={
                          task.priority === 'HIGH'
                            ? 'text-amber-600 dark:text-amber-400 font-medium'
                            : ''
                        }
                      >
                        {task.priority}
                      </span>
                      {task.autoGenerated && (
                        <>
                          <span>·</span>
                          <span className="text-blue-600 dark:text-blue-400">Auto-Followup</span>
                        </>
                      )}
                    </div>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>

        {/* Top Reps Leaderboard */}
        <div className="p-5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          <div className="flex items-center justify-between mb-4">
            <h2 className="font-display text-base font-semibold text-slate-900 dark:text-slate-100">
              {t(language, 'topReps')}
            </h2>
            <button
              onClick={() => setActiveModule('reports')}
              className="text-xs font-medium text-blue-600 dark:text-blue-400 hover:underline whitespace-nowrap"
            >
              Full Report
            </button>
          </div>
          <div className="divide-y divide-slate-100 dark:divide-slate-800">
            {data.leaderboard.map((rep, idx) => (
              <div key={rep.id} className="py-2.5 flex items-center justify-between gap-3">
                <div className="min-w-0">
                  <div className="text-sm font-medium text-slate-900 dark:text-slate-100 truncate">
                    0{idx + 1}. {rep.name}
                  </div>
                  <div className="text-xs text-slate-500 dark:text-slate-400">
                    {rep.dealsCount} deals · Open {formatCompactMoney(rep.pipelineAED, 'AED', currency)}
                  </div>
                </div>
                <div className="text-end shrink-0">
                  <div className="text-sm font-mono font-semibold tabular-nums text-emerald-600 dark:text-emerald-400">
                    {formatMoney(rep.wonAED, 'AED', currency)}
                  </div>
                  <div className="text-[11px] text-slate-400">Won</div>
                </div>
              </div>
            ))}
          </div>
        </div>

        {/* Upcoming Renewals */}
        <div className="p-5 rounded-xl bg-white dark:bg-slate-900 border border-slate-200 dark:border-slate-800">
          <div className="flex items-center justify-between mb-4">
            <h2 className="font-display text-base font-semibold text-slate-900 dark:text-slate-100">
              {t(language, 'upcomingRenewals')}
            </h2>
            <button
              onClick={() => setActiveModule('contracts')}
              className="text-xs font-medium text-blue-600 dark:text-blue-400 hover:underline whitespace-nowrap"
            >
              Contracts
            </button>
          </div>
          {data.upcomingRenewals.length === 0 ? (
            <div className="py-8 text-center text-xs text-slate-500 dark:text-slate-400">
              No contracts expiring within the next 90 days.
            </div>
          ) : (
            <div className="divide-y divide-slate-100 dark:divide-slate-800">
              {data.upcomingRenewals.map((r) => (
                <div key={r.id} className="py-2.5 flex items-center justify-between gap-3">
                  <div className="min-w-0">
                    <div className="text-sm font-medium text-slate-900 dark:text-slate-100 truncate">
                      {r.accountName}
                    </div>
                    <div className="text-xs text-slate-500 dark:text-slate-400 truncate">
                      {r.contractNumber} · {new Date(r.endDate).toLocaleDateString()}
                    </div>
                  </div>
                  <div className="text-end shrink-0">
                    <div
                      className={`text-xs font-mono font-semibold tabular-nums ${
                        r.daysLeft <= 30
                          ? 'text-red-600 dark:text-red-400'
                          : r.daysLeft <= 60
                            ? 'text-amber-600 dark:text-amber-400'
                            : 'text-slate-700 dark:text-slate-300'
                      }`}
                    >
                      {r.daysLeft}d left
                    </div>
                    <div className="text-[11px] font-mono tabular-nums text-slate-500">
                      {formatCompactMoney(r.arrAED, 'AED', currency)} ARR
                    </div>
                  </div>
                </div>
              ))}
            </div>
          )}
        </div>
      </div>
    </div>
  );
}
